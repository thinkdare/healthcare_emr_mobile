// Produces the exact outbox entries the real client writes, so the backend can
// be tested against them (healthcare-emr/tests/Feature/SyncFlutterContractTest.php).
//
// To regenerate the committed fixture after changing the entry format:
//   CONTRACT_FIXTURE_OUT=/path/to/healthcare-emr/tests/Fixtures/flutter_outbox_entries.json \
//     LD_LIBRARY_PATH=<dir with libsqlite3.so> flutter test test/localfirst/contract_fixture_test.dart
//
// Without the variable the test only checks the entries' shape.

import 'dart:convert';
import 'dart:io';

import 'package:flutter_test/flutter_test.dart';
import 'package:healthcare_emr_mobile/core/localfirst/local_store.dart';
import 'package:healthcare_emr_mobile/core/localfirst/vitals_repository.dart';
import 'package:sqflite_common_ffi/sqflite_ffi.dart';

import 'support/harness.dart';

const placeholder = 'PATIENT_ID_PLACEHOLDER';

void main() {
  initSqlite();

  test('the client writes entries in the format the contract specifies', () async {
    final dir = await Directory.systemTemp.createTemp('lfc_');
    final store = await LocalStore.open(path: '${dir.path}/c.db', factory: databaseFactoryFfi);
    final clock = DateTime.utc(2026, 10, 21, 9);
    final repo = VitalsRepository(store: store, userId: 'u', clock: () => clock, beforeWrite: () async => null);

    final first = await repo.record(patientId: placeholder, values: {'heart_rate': 72, 'temperature': 37.0, 'blood_pressure_systolic': 120, 'notes': 'Café ☕ / "quoted"'});
    await repo.amend(original: first.vital, corrections: {'heart_rate': 82});
    final bg = VitalsRepository(store: store, userId: 'u', clock: () => clock, beforeWrite: () async => 'Network outage on ward 3');
    await bg.record(patientId: placeholder, values: {'heart_rate': 90});

    final entries = await store.pending();
    expect(entries, hasLength(3));

    for (final e in entries) {
      final change = jsonDecode(e.body) as Map<String, dynamic>;
      expect(change.keys.toSet(), {'id', 'schema_version', 'resource_type', 'resource_id', 'operation', 'client_version', 'client_timestamp', 'payload'});
      expect(change['resource_type'], 'vitals');
      expect(change['operation'], 'create');
      expect(change['id'], matches(RegExp(r'^[0-9a-f]{8}-[0-9a-f]{4}-7[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$')));
      expect(change['resource_id'], matches(RegExp(r'^[0-9a-f]{8}-[0-9a-f]{4}-7[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$')));
      expect((change['payload'] as Map)['patient_id'], placeholder);
    }

    expect((jsonDecode(entries[1].body) as Map)['payload']['amends_id'], entries[0].resourceId);
    expect((jsonDecode(entries[2].body) as Map)['payload']['break_glass_reason'], 'Network outage on ward 3');

    final out = Platform.environment['CONTRACT_FIXTURE_OUT'];
    if (out != null) {
      File(out)
        ..createSync(recursive: true)
        ..writeAsStringSync(const JsonEncoder.withIndent('  ').convert({
          'note': 'Generated by healthcare_emr_mobile/test/localfirst/contract_fixture_test.dart. Each "body" is the exact text the Flutter outbox stores and sends.',
          'patient_placeholder': placeholder,
          'entries': [for (final e in entries) {'name': e.resourceId, 'body': e.body}],
        }));
    }

    await store.close();
    await dir.delete(recursive: true);
  });
}
